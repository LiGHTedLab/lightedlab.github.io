  // Colour every "LiGHT" letter by letter, as on the lab logo and nameboard.
  function brandify(root) {
    const skip = /^(SCRIPT|STYLE|TEXTAREA|INPUT|TITLE|OPTION)$/;
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
      acceptNode: (n) => (n.nodeValue.includes("LiGHT") && !skip.test(n.parentNode.nodeName) && !n.parentNode.closest(".light-word")
        ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT),
    });
    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    nodes.forEach((n) => {
      const frag = document.createDocumentFragment();
      n.nodeValue.split("LiGHT").forEach((part, i) => {
        if (i) {
          const w = document.createElement("span");
          w.className = "light-word";
          w.innerHTML = '<span class="lL">L</span><span class="li">i</span><span class="lG">G</span><span class="lH">H</span><span class="lT">T</span>';
          frag.appendChild(w);
        }
        if (part) frag.appendChild(document.createTextNode(part));
      });
      n.parentNode.replaceChild(frag, n);
    });
  }

