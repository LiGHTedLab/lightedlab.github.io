  /* ---------- Publications ---------- */
  const TYPE_LABEL = { journal: "Journal", conference: "Conference", preprint: "Preprint", chapter: "Chapter", other: "Other" };

  function authorsHtml(p) {
    const list = p.authors.map((a) => {
      const me = SELF.test(a);
      let s = esc(a);
      if (me) s = `<b>${s}${p.cofirst ? "<sup>†</sup>" : ""}${p.corresponding ? "<sup>*</sup>" : ""}</b>`;
      return s;
    });
    return list.join(", ");
  }

  function venueHtml(p) {
    let s = `<i>${esc(p.venue)}</i>`;
    if (p.volume) s += ` ${esc(p.volume)}`;
    if (p.issue) s += `(${esc(p.issue)})`;
    if (p.pages) s += `${p.volume || p.issue ? ", " : " "}${esc(p.pages)}`;
    return s + ` (${p.year})`;
  }

  function bib(p) {
    const kind = { journal: "article", conference: "inproceedings", preprint: "misc" }[p.type] || "misc";
    const vf = { journal: "journal", conference: "booktitle", preprint: "howpublished" }[p.type] || "note";
    const key = (p.authors[0].split(" ").pop().replace(/[^A-Za-z]/g, "") || "ref") + p.year + (p.title.split(" ")[0].replace(/[^A-Za-z]/g, "").toLowerCase());
    const f = [["title", `{${p.title}}`], ["author", p.authors.join(" and ")], [vf, p.venue], ["year", p.year], ["volume", p.volume], ["number", p.issue], ["pages", p.pages], ["doi", p.doi]];
    return `@${kind}{${key},\n${f.filter(([, v]) => v).map(([k, v]) => `  ${k} = {${v}}`).join(",\n")}\n}`;
  }

  const highlight = (html, q) => {
    if (!q) return html;
    const re = new RegExp(`(${q.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")})`, "gi");
    return html.replace(/>([^<]+)</g, (m, t) => ">" + t.replace(re, "<mark>$1</mark>") + "<");
  };

